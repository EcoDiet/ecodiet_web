create table dim_allergene (
  allergene_id integer primary key,
  libelle text not null
);

create table dim_equipement (
  equipement_id integer primary key,
  nom_equipement text not null
);

create table dim_ingredient (
  ingredient_id integer primary key,
  nom_ingredient text not null
);

create table dim_occasion (
  occasion_id integer primary key,
  libelle text not null
);

create table dim_regime (
  regime_id integer primary key,
  libelle text not null
);

create table dim_type_plat (
  type_plat_id integer primary key,
  libelle text not null
);

create table dim_temps_bin (
  temps_bin_id integer primary key,
  libelle text not null,
  min_minutes integer not null,
  max_minutes integer not null
);

create table fact_recette_base (
  recette_id text primary key,
  titre text not null,
  photo text default '',
  etapes text default '',
  duree_minute integer not null,
  temps_bin_id integer references dim_temps_bin(temps_bin_id)
);

create table fact_ingredients_recette (
  recette_id text not null references fact_recette_base(recette_id) on delete cascade,
  ingredient_id integer not null references dim_ingredient(ingredient_id) on delete cascade,
  primary key (recette_id, ingredient_id)
);

create table fact_recette_allergene (
  recette_id text not null references fact_recette_base(recette_id) on delete cascade,
  allergene_id integer not null references dim_allergene(allergene_id) on delete cascade,
  primary key (recette_id, allergene_id)
);

create table fact_recette_equipement (
  recette_id text not null references fact_recette_base(recette_id) on delete cascade,
  equipement_id integer not null references dim_equipement(equipement_id) on delete cascade,
  primary key (recette_id, equipement_id)
);

create table fact_recette_occasion (
  recette_id text not null references fact_recette_base(recette_id) on delete cascade,
  occasion_id integer not null references dim_occasion(occasion_id) on delete cascade,
  primary key (recette_id, occasion_id)
);

create table fact_recette_regime (
  recette_id text not null references fact_recette_base(recette_id) on delete cascade,
  regime_id integer not null references dim_regime(regime_id) on delete cascade,
  primary key (recette_id, regime_id)
);

create table fact_recette_type_plat (
  recette_id text not null references fact_recette_base(recette_id) on delete cascade,
  type_plat_id integer not null references dim_type_plat(type_plat_id) on delete cascade,
  primary key (recette_id, type_plat_id)
);

create table utilisateurs (
  user_id uuid primary key default auth.uid() references auth.users(id) on delete cascade,
  email text not null unique,
  nom text,
  prenom text,
  date_creation timestamptz not null default now()
);

create table user_favorite (
  user_id uuid not null references auth.users(id) on delete cascade,
  recette_id text not null references fact_recette_base(recette_id) on delete cascade,
  added_at timestamptz not null default now(),
  primary key (user_id, recette_id)
);

create table user_folder (
  folder_id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  label text not null,
  color bigint not null,
  created_at timestamptz not null default now(),
  unique (user_id, label)
);

create table folder_recette (
  folder_id bigint not null references user_folder(folder_id) on delete cascade,
  recette_id text not null references fact_recette_base(recette_id) on delete cascade,
  added_at timestamptz not null default now(),
  primary key (folder_id, recette_id)
);

create table user_regime (
  user_id uuid not null references auth.users(id) on delete cascade,
  regime_id integer not null references dim_regime(regime_id) on delete cascade,
  primary key (user_id, regime_id)
);

create table user_allergene (
  user_id uuid not null references auth.users(id) on delete cascade,
  allergene_id integer not null references dim_allergene(allergene_id) on delete cascade,
  primary key (user_id, allergene_id)
);

create table user_history (
  history_id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  recette_id text not null references fact_recette_base(recette_id) on delete cascade,
  viewed_at timestamptz not null default now()
);

create table quiz (
  quiz_id bigint generated by default as identity primary key,
  title text not null,
  description text,
  image_url text,
  difficulty integer not null default 1
);

create table quiz_question (
  question_id bigint generated by default as identity primary key,
  quiz_id bigint not null references quiz(quiz_id) on delete cascade,
  question_text text not null,
  explanation text,
  order_index integer not null default 0
);

create table quiz_option (
  option_id bigint generated by default as identity primary key,
  question_id bigint not null references quiz_question(question_id) on delete cascade,
  option_text text not null,
  is_correct boolean not null default false,
  order_index integer not null default 0
);

create table user_quiz_score (
  score_id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  quiz_id bigint not null references quiz(quiz_id) on delete cascade,
  score integer not null,
  total_questions integer not null,
  completed_at timestamptz not null default now()
);

create index idx_recette_temps on fact_recette_base(temps_bin_id);
create index idx_recette_duree on fact_recette_base(duree_minute);
create index idx_recette_titre on fact_recette_base using gin (to_tsvector('simple', titre));
create index idx_user_favorite_user on user_favorite(user_id);
create index idx_user_folder_user on user_folder(user_id);
create index idx_folder_recette_folder on folder_recette(folder_id);
create index idx_user_history_user on user_history(user_id, viewed_at desc);

